import { test, expect } from './fixtures'
import AxeBuilder from '@axe-core/playwright'

for (const mobile of [false, true]) {
  test(`RGB curves edit, drag, render and reset on ${mobile ? 'mobile' : 'desktop'}`, async ({ page }, testInfo) => {
    await page.setViewportSize(mobile ? {width:390,height:844} : {width:1440,height:1000})
    await page.goto('/studio')
    await page.getByText('RGB Curves', {exact:false}).click()
    await expect(page.getByRole('button',{name:'Add point',exact:true})).toBeDisabled()
    await page.getByRole('button',{name:'Try a sample photograph'}).click()
    const exportButton = page.getByRole('button',{name:'Export image',exact:true})
    await expect(exportButton).toBeEnabled()
    await page.getByRole('button',{name:'Add point',exact:true}).click()
    await expect(page.getByLabel('Input',{exact:true})).toHaveValue('128')
    const preview = page.waitForResponse(r => r.url().endsWith('/preview') && r.status() === 200)
    await page.getByLabel('Output',{exact:true}).fill('170')
    const body = (await preview).request().postDataJSON()
    expect(body.curves.rgb.points).toEqual([{x:0,y:0},{x:128,y:170},{x:255,y:255}])
    await expect(exportButton).toBeEnabled()
    const handle = page.getByRole('button',{name:'RGB point 2:',exact:false})
    await handle.focus()
    await page.keyboard.press('ArrowUp')
    await expect(page.getByLabel('Output',{exact:true})).toHaveValue('171')
    const box = await handle.boundingBox()
    await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2)
    await page.mouse.down()
    await page.mouse.move(box!.x+box!.width/2+10,box!.y+box!.height/2-10,{steps:5})
    await page.mouse.up()
    expect(Number(await page.getByLabel('Output',{exact:true}).inputValue())).toBeGreaterThan(171)
    await page.getByRole('button',{name:'Red',exact:true}).click()
    await page.getByRole('button',{name:'Add point',exact:true}).click()
    await page.getByLabel('Output',{exact:true}).fill('150')
    await expect(exportButton).toBeEnabled()
    expect((await new AxeBuilder({page}).include('aside[aria-label="Image adjustments"]').analyze()).violations).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({path:testInfo.outputPath(`curves-${mobile ? 'mobile':'desktop'}.png`),fullPage:true})
    const detailRequest = page.waitForRequest(r => r.url().endsWith('/export'))
    await page.getByRole('button',{name:'100% detail',exact:true}).click()
    const detailBody = (await detailRequest).postDataJSON()
    expect(detailBody.curves.red.points[1]).toEqual({x:128,y:150})
    await expect(page.getByAltText('Full-resolution enhanced photograph')).toBeVisible()
    await page.getByRole('button',{name:'Close detail view'}).click()
    await exportButton.click()
    const exportRequest = page.waitForRequest(r => r.url().endsWith('/export'))
    const download = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download JPEG'}).click()
    expect((await exportRequest).postDataJSON().curves).toEqual(detailBody.curves)
    expect(await (await download).failure()).toBeNull()
    await page.getByRole('button',{name:'Reset Red curve',exact:true}).click()
    await expect(page.getByRole('button',{name:'Red point',exact:false})).toHaveCount(2)
    await page.getByRole('button',{name:'RGB',exact:true}).click()
    await expect(page.getByRole('button',{name:'RGB point',exact:false})).toHaveCount(3)
    await page.getByRole('button',{name:'RGB point 2:',exact:false}).press('Delete')
    await expect(page.getByRole('button',{name:'RGB point',exact:false})).toHaveCount(2)
    await expect(page.getByRole('button',{name:'Reset adjustments',exact:true})).toBeDisabled()
  })
}
