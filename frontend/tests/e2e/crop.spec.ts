import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

// Optional isolated target lets this test coexist with a live editing session.
test.beforeEach(async ({ page }) => {
  const target = process.env.CROP_TEST_API
  if (target) await page.route('**/api/**', async route => {
    const original = new URL(route.request().url())
    const response = await route.fetch({ url: `${target}${original.pathname}${original.search}` })
    await route.fulfill({ response })
  })
})

test('crop applies to previews and JPEG export while presets and reset keep the frame', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  const original = await page.locator('img[alt="alpine-perspective.jpg"]').evaluate((img: HTMLImageElement) => ({ width: img.naturalWidth, height: img.naturalHeight }))
  await page.getByRole('button', { name: 'Crop', exact: true }).click()
  await page.getByLabel('Aspect ratio', { exact: true }).selectOption('1:1')
  const width = Number(await page.getByLabel('Width (px)', { exact: true }).inputValue())
  const height = Number(await page.getByLabel('Height (px)', { exact: true }).inputValue())
  expect(width).toBe(height)
  const accessibility = await new AxeBuilder({ page }).include('dialog[open]').analyze()
  expect(accessibility.violations).toEqual([])
  await page.getByRole('button', { name: 'Apply crop' }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await expect.poll(async () => page.locator('img[alt="alpine-perspective.jpg"] + div img').evaluate((img: HTMLImageElement) => img.naturalWidth / img.naturalHeight)).toBeCloseTo(1, 1)
  await page.getByRole('button', { name: /Golden Hour/ }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await page.getByRole('button', { name: 'Reset adjustments', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await expect(page.getByLabel('Before and after comparison position')).toBeVisible()
  await page.getByRole('button', { name: 'Export image' }).click()
  await expect(page.getByRole('dialog')).toContainText(`${width} × ${height}`)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JPEG' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(chunk)
  const bytes = Buffer.concat(chunks)
  const dimensions = await page.evaluate(async data => {
    const image = await createImageBitmap(new Blob([new Uint8Array(data)], { type: 'image/jpeg' }))
    const size = [image.width, image.height]; image.close(); return size
  }, [...bytes])
  expect(dimensions).toEqual([width, height])
  await page.getByRole('button', { name: 'Crop', exact: true }).click()
  await page.getByRole('button', { name: 'Reset crop' }).click()
  await page.getByRole('button', { name: 'Apply crop' }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await expect.poll(async () => page.locator('img[alt="alpine-perspective.jpg"]').evaluate((img: HTMLImageElement) => img.naturalWidth / img.naturalHeight)).toBeCloseTo(original.width / original.height)
  expect(errors).toEqual([])
  await page.goto('/')
})

test('mobile crop supports keyboard movement, bounded resizing, cancellation and focus restoration', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  const cropButton = page.getByRole('button', { name: 'Crop', exact: true })
  await cropButton.click()
  await page.getByLabel('Aspect ratio', { exact: true }).selectOption('9:16')
  const left = Number(await page.getByLabel('Left (px)').inputValue())
  await page.getByRole('button', { name: 'Move crop selection' }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByLabel('Left (px)')).toHaveValue(String(left + 1))
  await page.getByLabel('Aspect ratio', { exact: true }).selectOption('free')
  const selection = page.getByRole('button', { name: 'Move crop selection' })
  const before = await selection.boundingBox()
  const corner = await page.getByRole('button', { name: 'Resize crop se' }).boundingBox()
  await page.mouse.move(corner!.x + corner!.width / 2, corner!.y + corner!.height / 2)
  await page.mouse.down()
  await page.mouse.move(corner!.x - 12, corner!.y - 12, { steps: 4 })
  await page.mouse.up()
  const after = await selection.boundingBox()
  expect(after!.width).toBeLessThan(before!.width)
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('crop-mobile.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await expect(cropButton).toBeFocused()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await cropButton.click()
  await page.getByLabel('Aspect ratio', { exact: true }).selectOption('free')
  await expect(page.getByLabel('Left (px)')).toHaveValue('0')
  await page.getByRole('button', { name: 'Apply crop' }).click()
  await expect(page.getByRole('button', { name: 'Export image' })).toBeEnabled()
  await page.goto('/')
})
