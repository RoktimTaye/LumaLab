import { test, expect } from './fixtures'
import AxeBuilder from '@axe-core/playwright'
import path from 'node:path'

test('enhancement strength, manual edits, export and reset share the accepted recipe', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  const exportButton = page.getByRole('button', { name: 'Export image', exact: true })
  await expect(exportButton).toBeEnabled()
  const editedImage = page.locator('img[alt="alpine-perspective.jpg"] + div img')
  const originalUrl = await editedImage.getAttribute('src')
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  const analysisResponse = page.waitForResponse(response => response.url().endsWith('/enhance') && response.status() === 200)
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  const firstRecipe = (await (await analysisResponse).json()).recipe
  const strength = page.getByLabel('Auto Enhance strength', { exact: true })
  await expect(strength).toHaveValue('100')
  await expect(exportButton).toBeEnabled()
  await expect(page.getByText('Editing decisions', { exact: true })).toBeVisible()
  expect(firstRecipe.version).toBe('natural-v3')
  expect(await editedImage.getAttribute('src')).not.toBe(originalUrl)
  const accessibility = await new AxeBuilder({ page }).include('aside[aria-label="Image adjustments"]').analyze()
  expect(accessibility.violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('natural-enhancement-desktop.png'), fullPage: true })

  // Zero strength uses the untouched original and does not reset manual edits.
  await strength.fill('0')
  await expect(exportButton).toBeEnabled()
  await expect(editedImage).toHaveAttribute('src', originalUrl!)
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/preview') && response.status() === 200)
  await strength.fill('40')
  const preview = await previewResponse
  expect(preview.request().postDataJSON().enhancement.strength).toBe(0.4)
  await expect(exportButton).toBeEnabled()
  const manualPreviewResponse = page.waitForResponse(response => response.url().endsWith('/preview') && response.status() === 200)
  await page.getByLabel('Brightness', { exact: true }).fill('110')
  const manualBody = (await manualPreviewResponse).request().postDataJSON()
  expect(manualBody.enhancement.strength).toBe(0.4)
  expect(manualBody.adjustments.brightness).toBe(110)
  await expect(exportButton).toBeEnabled()
  await exportButton.click()
  const exportRequest = page.waitForRequest(request => request.url().endsWith('/export'))
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JPEG' }).click()
  const exportBody = (await exportRequest).postDataJSON()
  expect(exportBody.enhancement).toEqual(manualBody.enhancement)
  expect(exportBody.adjustments).toEqual(manualBody.adjustments)
  expect(await (await downloadPromise).failure()).toBeNull()

  // Re-running analysis must derive the same base from the original.
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  const nextAnalysis = page.waitForResponse(response => response.url().endsWith('/enhance') && response.status() === 200)
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  expect((await (await nextAnalysis).json()).recipe).toEqual(firstRecipe)
  await expect(strength).toHaveValue('100')
  await expect(page.getByLabel('Brightness', { exact: true })).toHaveValue('100')
  await page.getByRole('button', { name: /Vivid/ }).click()
  await expect(strength).toHaveCount(0)
  await expect(page.getByText('Editing decisions', { exact: true })).toHaveCount(0)
  await expect(exportButton).toBeEnabled()
  await page.getByRole('button', { name: 'Reset adjustments', exact: true }).click()
  await expect(editedImage).toHaveAttribute('src', originalUrl!)
  await expect(exportButton).toBeEnabled()
})

test('tea garden receives a visible deficit/excess plan that survives crop and export', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/studio')
  await page.getByLabel('Photograph file', { exact: true }).setInputFiles(path.resolve('public/images/tea-garden-background.jpg'))
  const exportButton = page.getByRole('button', { name: 'Export image', exact: true })
  await expect(exportButton).toBeEnabled()
  const edited = page.locator('img[alt="tea-garden-background.jpg"] + div img')
  const original = await edited.getAttribute('src')
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/enhance') && response.status() === 200)
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  const result = await (await responsePromise).json()
  await expect(exportButton).toBeEnabled()
  await page.getByText('Editing decisions', { exact: true }).click()
  await expect(page.getByText('Strong green saturation', { exact: true })).toBeVisible()
  await expect(page.getByText('Lifted darkest tones', { exact: true })).toBeVisible()
  expect(result.recipe.black_point).toBeGreaterThan(0.02)
  expect(result.recipe.hue_chroma[2]).toBeLessThan(-0.08)
  expect(result.recipe.local_exposure).toHaveLength(64)
  const enhanced = await edited.getAttribute('src')
  const difference = await page.evaluate(async ({ before, after }) => {
    const pixels = async (url: string) => {
      const image = await createImageBitmap(await (await fetch(url)).blob())
      const canvas = document.createElement('canvas'); canvas.width = 512; canvas.height = 320
      const ctx = canvas.getContext('2d')!; ctx.drawImage(image, 0, 0, 512, 320); image.close()
      return ctx.getImageData(0, 0, 512, 320).data
    }
    const a = await pixels(before), b = await pixels(after)
    let sum = 0
    for (let i = 0; i < a.length; i++) if (i % 4 !== 3) sum += Math.abs(a[i] - b[i])
    return sum / (a.length / 4 * 3)
  }, { before: original!, after: enhanced! })
  expect(difference).toBeGreaterThan(5)
  const accessibility = await new AxeBuilder({ page }).include('aside[aria-label="Image adjustments"]').analyze()
  expect(accessibility.violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('tea-garden-photographic-v2.png'), fullPage: true })
  await page.getByRole('button', { name: 'Crop', exact: true }).click()
  await page.getByLabel('Aspect ratio', { exact: true }).selectOption('1:1')
  const cropPreview = page.waitForResponse(response => response.url().endsWith('/preview') && response.status() === 200)
  await page.getByRole('button', { name: 'Apply crop' }).click()
  const previewBody = (await cropPreview).request().postDataJSON()
  expect(previewBody.enhancement).toEqual(result.recipe)
  expect(previewBody.crop.width).toBe(previewBody.crop.height)
  await expect(exportButton).toBeEnabled()
  await exportButton.click()
  const exportRequest = page.waitForRequest(request => request.url().endsWith('/export'))
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JPEG' }).click()
  const body = (await exportRequest).postDataJSON()
  expect(body.enhancement).toEqual(result.recipe)
  expect(body.crop).toEqual(previewBody.crop)
  expect(await (await downloadPromise).failure()).toBeNull()
})

test('a late enhancement cannot overwrite manual edits and mobile strength stays accessible', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  await expect(page.getByRole('button', { name: 'Export image', exact: true })).toBeEnabled()
  let release!: () => void
  const started = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/v1/images/*/enhance', async route => {
    const response = await route.fetch()
    release()
    await new Promise(resolve => setTimeout(resolve, 500))
    await route.fulfill({ response }).catch(() => {})
  })
  await page.getByRole('button', { name: 'Presets & upload' }).click()
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  await started
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Adjustments', exact: true }).click()
  await page.getByLabel('Brightness', { exact: true }).fill('112')
  await expect(page.getByRole('button', { name: 'Export image', exact: true })).toBeEnabled()
  await page.waitForTimeout(600)
  await expect(page.getByLabel('Brightness', { exact: true })).toHaveValue('112')
  await expect(page.getByLabel('Auto Enhance strength', { exact: true })).toHaveCount(0)
  await page.unroute('**/api/v1/images/*/enhance')
  await page.getByRole('button', { name: 'Presets & upload' }).click()
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  await page.getByRole('button', { name: 'Adjustments', exact: true }).click()
  await expect(page.getByLabel('Auto Enhance strength', { exact: true })).toHaveValue('100')
  await expect(page.getByRole('button', { name: 'Export image', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('natural-enhancement-mobile.png'), fullPage: true })
})
