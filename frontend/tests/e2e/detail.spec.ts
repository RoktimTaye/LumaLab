import { test, expect } from './fixtures'
import AxeBuilder from '@axe-core/playwright'

test('100% detail shows the actual export at natural pixel dimensions and releases it on close', async ({ page }, testInfo) => {
  test.setTimeout(90_000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  await expect(page.getByRole('button', { name: 'Export image', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Auto Enhance', exact: true }).click()
  await page.getByRole('button', { name: 'Apply suggestions' }).click()
  const detailButton = page.getByRole('button', { name: '100% detail', exact: true })
  await expect(detailButton).toBeEnabled()
  const exportRequest = page.waitForRequest(request => request.url().endsWith('/export'))
  await detailButton.click()
  expect((await exportRequest).postDataJSON().enhancement.version).toBe('natural-v3')
  const dialog = page.getByRole('dialog', { name: '100% detail', exact: true })
  const image = dialog.getByAltText('Full-resolution enhanced photograph', { exact: true })
  // This intentionally waits for the full-resolution renderer, not a proxy.
  await expect(image).toBeVisible({ timeout: 60_000 })
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBeTruthy()
  const dimensions = await image.evaluate((element: HTMLImageElement) => ({
    width: element.width, height: element.height, naturalWidth: element.naturalWidth, naturalHeight: element.naturalHeight,
  }))
  expect(dimensions.width).toBe(dimensions.naturalWidth)
  expect(dimensions.height).toBe(dimensions.naturalHeight)
  expect(dimensions.naturalWidth).toBe(1600)
  const accessibility = await new AxeBuilder({ page }).include('dialog[open]').analyze()
  expect(accessibility.violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('full-resolution-detail.png') })
  const blobUrl = await image.getAttribute('src')
  await page.getByRole('button', { name: 'Close detail view', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(detailButton).toBeFocused()
  expect(await page.evaluate(url => fetch(url!).then(() => false, () => true), blobUrl)).toBeTruthy()
})

test('mobile detail scrolls at 100% and a failed render can be closed safely', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/studio')
  await page.getByRole('button', { name: 'Try a sample photograph' }).click()
  const detailButton = page.getByRole('button', { name: '100% detail', exact: true })
  await expect(detailButton).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.route('**/api/v1/images/*/export', route => route.fulfill({ status: 503, contentType: 'application/json',
    body: JSON.stringify({ error: { code: 'service_unavailable', message: 'Detail render unavailable.' } }) }))
  await detailButton.click()
  await expect(page.getByRole('dialog').getByRole('alert')).toHaveText('Detail render unavailable.')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(detailButton).toBeFocused()
  await page.unroute('**/api/v1/images/*/export')
  await detailButton.click()
  await expect(page.getByAltText('Full-resolution enhanced photograph', { exact: true })).toBeVisible()
  const viewport = page.getByLabel('Full-resolution photograph; scroll to inspect detail', { exact: true })
  expect(await viewport.evaluate(element => element.scrollWidth > element.clientWidth)).toBeTruthy()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.keyboard.press('Escape')
})
