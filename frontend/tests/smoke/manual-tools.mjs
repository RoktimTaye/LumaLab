import { chromium } from '@playwright/test'
const browser=await chromium.launch({channel:'chrome',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try{
 await page.goto(`${process.env.STUDIO_TEST_URL ?? 'http://127.0.0.1:5176'}/studio`)
 await page.getByLabel('Photograph file').setInputFiles('public/images/alpine.jpg')
 await page.locator('#exposure:enabled').waitFor()
 await page.locator('#exposure').fill('1')
 await page.waitForTimeout(350)
 await page.getByRole('button',{name:'Undo edit',exact:true}).click()
 if(await page.locator('#exposure').inputValue()!=='0')throw new Error('Undo failed')
 await page.getByRole('button',{name:'Redo edit',exact:true}).click()
 if(await page.locator('#exposure').inputValue()!=='1')throw new Error('Redo failed')
 await page.getByText('Rotate & straighten',{exact:true}).click()
 await page.getByRole('button',{name:'Rotate right',exact:true}).click()
 await page.locator('#straighten').fill('10')
 await page.waitForTimeout(2000)
 if(!await page.getByRole('button',{name:'Export image',exact:true}).isEnabled())throw new Error('Geometry preview failed')
 const size=await page.evaluate(()=>({height:innerHeight,scroll:document.documentElement.scrollHeight}))
 if(size.scroll>size.height+2)throw new Error('Desktop page scrolls')
 await page.getByRole('button',{name:'White balance eyedropper / auto'}).click()
 await page.getByRole('button',{name:'Auto white balance',exact:true}).click()
 await page.waitForTimeout(1000)
 await page.setViewportSize({width:390,height:844})
 const mobile=await page.evaluate(()=>({height:innerHeight,scroll:document.documentElement.scrollHeight,width:innerWidth,scrollWidth:document.documentElement.scrollWidth}))
 if(mobile.scroll>mobile.height+2||mobile.scrollWidth>mobile.width+2)throw new Error('Mobile overflows viewport')
 await page.screenshot({path:'manual-tools-mobile.png'})
 if(errors.length)throw new Error(errors.join('\n'))
 console.log('Browser checks passed: upload, exposure, undo/redo, rotate, straighten, preview readiness, auto WB and viewport fit.')
}finally{await browser.close()}

